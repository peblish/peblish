import { localActorUrls } from '@peblish/schema/actor-urls';
import type { Principal } from '@peblish/schema/authz';
import type { Uuid } from '@peblish/schema/ids';
import { type } from 'arktype';
import { uuidv7 } from 'uuidv7';
import { newRsaKeyPair } from '../actor-keys.ts';
import { authorize } from '../authz/authorize.ts';
import { localInstance } from '../db/local-instance.ts';
import { actorKeys, actors } from '../db/tables/actors.ts';
import { communityModerators } from '../db/tables/moderation.ts';
import { uniqueViolation } from '../identity/accounts.ts';
import { refusedAsResult, type Result } from '../identity/result.ts';
import { writeModlog } from '../modlog/write.ts';
import { defineMutation } from '../tx/mutation.ts';
import { Refused } from '../tx/refused.ts';
import { markdown, replaceLanguages, replaceRules } from './fields.ts';
import { CommunityInput, type CommunityPatch } from './input.ts';

const Keys = type({ publicKeyPem: 'string', privateKeyPem: 'string' });

/**
 * Creates a local community (a Group actor) in one transaction: the actor with its endpoints,
 * its RSA-2048 signing key (generated by the caller, before the transaction opens), its
 * languages and rules, the creating admin as its owner, and a modlog row naming the admin
 * (action community.create, like community.set_moderator). The name comes from the grant.
 * featured_url and moderators_url sit below the ap_id like the other endpoints, for federation
 * to serve. A name another create took first is refused with name.taken, not a raw unique
 * violation.
 */
export const createCommunity = defineMutation({
  action: 'community.create',
  emits: ['actor.created'],
  recheck: true,
  async run(t, grant, input: { fields: CommunityPatch; keys: { publicKeyPem: string; privateKeyPem: string } }) {
    const fields = CommunityInput.assert(input.fields);
    const keys = Keys.assert(input.keys);
    const { name } = grant.subject;
    const instance = await localInstance(t.db);
    const urls = localActorUrls(instance.origin, 'Group', name);
    const summary = markdown(fields.description, instance.origin);
    const nsfl = fields.nsfl ?? false;
    const id = uuidv7();
    const now = new Date();
    try {
      await t.db.insert(actors).values({
        id,
        apId: urls.apId,
        kind: 'Group',
        local: true,
        instanceId: instance.id,
        name,
        displayName: fields.displayName ?? null,
        summaryMd: summary.md,
        summaryHtml: summary.html,
        inboxUrl: urls.inbox,
        outboxUrl: urls.outbox,
        followersUrl: urls.followers,
        sharedInboxUrl: urls.sharedInbox,
        featuredUrl: `${urls.apId}/featured`,
        moderatorsUrl: `${urls.apId}/moderators`,
        // Not safe for life is stricter than NSFW, so the age gate covers it.
        sensitive: (fields.sensitive ?? false) || nsfl,
        nsfl,
        postingRestrictedToMods: fields.postingRestrictedToMods ?? false,
        postingWarning: fields.postingWarning || null,
        publishedAt: now,
      });
    } catch (error) {
      const constraint = uniqueViolation(error);
      if (constraint === 'actors_local_name_unique' || constraint === 'actors_ap_id_unique')
        throw new Refused('community.create', 'name.taken');
      throw error;
    }
    await t.db.insert(actorKeys).values({ actorId: id, keyId: urls.keyId, algorithm: 'rsa', ...keys });
    await replaceLanguages(t.db, id, fields.languages ?? []);
    await replaceRules(t.db, id, instance.origin, fields.rules ?? []);
    await t.db
      .insert(communityModerators)
      .values({ communityId: id, moderatorId: grant.actorId, role: 'owner', source: 'local', verifiedAt: now });
    await writeModlog(t.db, grant, { community: { id, apId: urls.apId }, target: null, reason: null });
    await t.emit({ type: 'actor.created', v: 1, actorId: id, kind: 'Group', local: true });
    return { id, name, apId: urls.apId };
  },
});

/**
 * community.create for web: authorize first, so only an admin with two-factor and a usable
 * name spends a keypair's worth of CPU, then check the fields (`community.invalid`), generate
 * the key outside the transaction and create.
 */
export async function createCommunityAs(
  principal: Principal,
  input: { name: string } & CommunityPatch,
): Promise<Result<{ id: Uuid; name: string; apId: string }>> {
  const { name, ...fields } = input;
  const decision = await authorize('community.create', principal, { name });
  if (!decision.ok) return decision;
  if (CommunityInput(fields) instanceof type.errors) return { ok: false, reason: 'community.invalid' };
  const keys = await newRsaKeyPair();
  return refusedAsResult(() => createCommunity(decision.grant, { fields, keys }));
}
